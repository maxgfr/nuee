/** @type {Record<Lang, Record<string, string>>} */
export const DICTS = { en, fr };

const STORAGE_KEY = 'nuee.lang';
/** @type {Lang} */
let lang = 'en';
/** @type {Set<(l: Lang) => void>} */
const listeners = new Set();

/** @param {string} s @returns {s is Lang} */
function isLang(s) {
  return s === 'en' || s === 'fr';
}

/**
 * The language for a list of preferred languages (navigator.languages): French when the
 * first known one is French, English otherwise.
 * @param {readonly string[]} prefs
 * @returns {Lang}
 */
export function pickLang(prefs) {
  for (const p of prefs) {
    const base = p.toLowerCase().split('-')[0] ?? '';
    if (isLang(base)) return base;
  }
  return 'en';
}

export function getLang() {
  return lang;
}

/**
 * Translates `key`, replacing `{name}` placeholders. A missing key shows the key itself so
 * it is noticed, and is logged.
 * @param {string} key
 * @param {Record<string, string | number>} [vars]
 */
export function t(key, vars) {
  const s = DICTS[lang][key] ?? en[key];
  if (s === undefined) {
    console.error(`missing string ${key}`);
    return key;
  }
  return vars ? s.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m)) : s;
}

/** @param {(l: Lang) => void} fn */
export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** @param {Lang} l @param {boolean} [remember] */
export function setLang(l, remember = true) {
  lang = l;
  if (typeof document !== 'undefined') document.documentElement.lang = l;
  if (remember) {
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch (e) {
      console.warn('language preference not saved', e);
    }
  }
  for (const fn of listeners) fn(l);
}

export function toggleLang() {
  setLang(lang === 'fr' ? 'en' : 'fr');
}

/** Picks the saved language, else the browser's. @param {readonly string[]} prefs */
export function initLang(prefs) {
  /** @type {string | null} */
  let saved = null;
  try {
    saved = localStorage.getItem(STORAGE_KEY);
  } catch (e) {
    console.warn('language preference unavailable', e);
  }
  setLang(saved && isLang(saved) ? saved : pickLang(prefs), false);
}
