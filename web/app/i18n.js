/** The dictionary, exported for the tests that check it. */
export const STRINGS = en;

/**
 * Translates `key`, replacing `{name}` placeholders. A missing key shows the key itself so
 * it is noticed, and is logged.
 * @param {string} key
 * @param {Record<string, string | number>} [vars]
 */
export function t(key, vars) {
  const s = en[key];
  if (s === undefined) {
    console.error(`missing string ${key}`);
    return key;
  }
  return vars ? s.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m)) : s;
}
